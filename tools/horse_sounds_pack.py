# Packs the trimmed clips into scene/src/horse_sounds.cpp as 8-bit mu-law (G.711), 16 kHz.
import sys, wave, numpy as np
clips_dir, out = sys.argv[1], sys.argv[2]
names = ['neigh', 'nicker', 'snort', 'clop', 'munch', 'brush']
def mulaw(x):
    x = np.clip(x, -32635, 32635).astype(np.int32)
    sign = np.where(x < 0, 0x80, 0); x = np.abs(x) + 0x84
    exp = np.zeros_like(x)
    for e in range(7, -1, -1):
        exp = np.where((exp == 0) & (x >= (1 << (e + 7))), e, exp)
    mant = (x >> (exp + 3)) & 0x0F
    return (~(sign | (exp << 4) | mant)) & 0xFF
lines = ["// Generated by tools: real horse recordings for the horse edition, 16 kHz 8-bit mu-law.",
         "// From BigSoundBank.com (Joseph Sardin), released CC0 / public domain:",
         "//   Horse neighing #5 (1542), Little neighing call #2 (1213), Breath of a horse #1 (0285),",
         "//   Horse steps on concrete (0496), Horse eats carrot #3 (1847), Horsehair brush (1856).",
         "// Trimmed, levelled and the deep bass taken out for the board's small speaker.",
         '#include "horse_sounds.hpp"', "", "namespace squatch {", "namespace {", ""]
total = 0
for n in names:
    w = wave.open(f"{clips_dir}/horse-{n}.wav"); pcm = np.frombuffer(w.readframes(w.getnframes()), np.int16)
    u = mulaw(pcm.astype(np.int32)); total += len(u)
    lines.append(f"const uint8_t k_{n}[{len(u)}] = {{")
    for i in range(0, len(u), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in u[i:i + 20]) + ",")
    lines.append("};")
    lines.append("")
lines.append("}  // namespace")
lines.append("")
lines.append("const HorseClip kHorseClips[kHorseClipCount] = {")
for n in names:
    lines.append(f"    {{k_{n}, static_cast<int>(sizeof k_{n})}},")
lines.append("};")
lines.append("")
lines.append("}  // namespace squatch")
open(out, 'w').write("\n".join(lines) + "\n")
print("bytes", total)
