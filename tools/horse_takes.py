# More takes of the horse's sounds, so it doesn't make the very same one each time, plus
# eating sounds for hay and one rude noise. Real recordings from BigSoundBank.com (Joseph
# Sardin), CC0 / public domain; prepared like horse_sounds_prep.py (16 kHz, deep bass out,
# trimmed, levelled) and written as 8-bit mu-law clips.
# Usage: python3 horse_takes.py WAV_FOLDER scene/src/horse_takes.cpp [PREVIEW_DIR]
import glob, sys, wave
from math import gcd
import numpy as np
from scipy.signal import resample_poly, butter, sosfilt

RATE = 16000
src, out = sys.argv[1], sys.argv[2]
preview = sys.argv[3] if len(sys.argv) > 3 else None

def load(pattern):
    f = glob.glob(f"{src}/*{pattern}*")[0]
    w = wave.open(f); n = w.getnframes(); ch = w.getnchannels(); sw = w.getsampwidth(); fr = w.getframerate()
    raw = w.readframes(n)
    if sw == 3:
        b = np.frombuffer(raw, np.uint8).reshape(-1, 3)
        x = (b[:, 0].astype(np.int32) | (b[:, 1].astype(np.int32) << 8) | (b[:, 2].astype(np.int32) << 16))
        x = np.where(x & 0x800000, x - 0x1000000, x) / 8388608.0
    else:
        x = np.frombuffer(raw, np.int16) / 32768.0
    x = x.reshape(-1, ch).mean(axis=1)
    g = gcd(fr, RATE)
    x = resample_poly(x, RATE // g, fr // g)
    return sosfilt(butter(2, 140, 'highpass', fs=RATE, output='sos'), x)  # the little speaker can't do deep bass

def trim(x, db=-36):
    env = np.convolve(np.abs(x), np.ones(160) / 160, 'same')
    on = np.where(env > env.max() * 10 ** (db / 20))[0]
    return x[max(0, on[0] - 80): on[-1] + 400]

def window(x, secs):  # the loudest stretch of this length (or all of it, if it's shorter)
    n = int(secs * RATE)
    if len(x) <= n: return x
    e = np.convolve(x ** 2, np.ones(n), 'valid'); i = int(e.argmax()); return x[i:i + n]

def fade(x, inMs=5, outMs=60):
    a, b = int(RATE * inMs / 1000), int(RATE * outMs / 1000)
    x = x.copy(); x[:a] *= np.linspace(0, 1, a); x[-b:] *= np.linspace(1, 0, b); return x

def norm(x, peak): return x / np.abs(x).max() * peak

def call(pattern, secs, peak=0.92):  # one vocal sound: just the sound, at most this long
    return norm(fade(window(trim(load(pattern)), secs)), peak)

clips = {
    'neigh_b': call('Horse_neighing_3', 1.9), 'neigh_c': call('Horse_neighing_4', 1.9),
    'neigh_d': call('Neighing_of_a_horse_1', 1.9), 'neigh_e': call('Neighing_of_a_horse_ID_0460', 1.9),
    'nicker_b': call('neighing_call_1', 1.4, 0.9), 'nicker_c': call('neighing_call_3', 1.4, 0.9),
    'nicker_d': call('neighing_call_4', 1.4, 0.9), 'nicker_e': call('neighing_call_5', 1.4, 0.9),
    'snort_b': call('Breath_of_a_horse_2', 1.0, 0.9), 'snort_c': call('Breath_horse_3', 1.0, 0.9),
    'snort_d': call('Breath_horse_4', 1.0, 0.9),
    'munch_b': norm(fade(window(load('eats_carrot_2'), 1.3), 10, 120), 0.9),
    'hay_a': norm(fade(window(load('chewing_hay'), 1.4), 10, 150), 0.9),
    'hay_b': norm(fade(window(load('eating_grass_2'), 1.4), 10, 150), 0.9),
    'toot': call('flatulence_2', 1.6, 0.9),
}

def mulaw(x):
    x = np.clip(x, -32635, 32635).astype(np.int32)
    sign = np.where(x < 0, 0x80, 0); x = np.abs(x) + 0x84
    exp = np.zeros_like(x)
    for e in range(7, -1, -1):
        exp = np.where((exp == 0) & (x >= (1 << (e + 7))), e, exp)
    return (~(sign | (exp << 4) | ((x >> (exp + 3)) & 0x0F))) & 0xFF

lines = ["// Generated by tools/horse_takes.py: real recordings, 16 kHz 8-bit mu-law.",
         "// From BigSoundBank.com (Joseph Sardin), released CC0 / public domain: Horse neighing #3 (0863),",
         "//   Horse neighing #4 (1541), Neighing of a horse #1 (0284), Neighing of a horse (0460), Little",
         "//   neighing call #1, #3, #4, #5 (1212, 1214-1216), Breath of a horse #2 (0286), Breath horse #3, #4",
         "//   (0287, 1543), Horse eats carrot #2 (1846), Horse chewing hay (0497), Horse eating grass #2 (0990),",
         "//   Pony flatulence #2 (1855).",
         '#include "horse_sounds.hpp"', "", "namespace squatch {", "namespace {", ""]
for name, x in clips.items():
    pcm = (np.clip(x, -1, 1) * 32000).astype(np.int16)
    if preview:
        w = wave.open(f"{preview}/{name}.wav", 'wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE)
        w.writeframes(pcm.tobytes()); w.close()
    u = mulaw(pcm.astype(np.int32))
    lines.append(f"const uint8_t k_{name}[{len(u)}] = {{")
    for i in range(0, len(u), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in u[i:i + 20]) + ",")
    lines.append("};")
    lines.append("")
    print(f"{name:9s} {len(x) / RATE:.2f} s")
def clip(n): return f"{{k_{n}, static_cast<int>(sizeof k_{n})}}"
lines += ["}  // namespace", "",
          "const HorseClip kNeighTakes[4] = {" + ", ".join(clip(n) for n in ['neigh_b', 'neigh_c', 'neigh_d', 'neigh_e']) + "};",
          "const HorseClip kNickerTakes[4] = {" + ", ".join(clip(n) for n in ['nicker_b', 'nicker_c', 'nicker_d', 'nicker_e']) + "};",
          "const HorseClip kSnortTakes[3] = {" + ", ".join(clip(n) for n in ['snort_b', 'snort_c', 'snort_d']) + "};",
          "const HorseClip kMunchTakes[1] = {" + clip('munch_b') + "};",
          "const HorseClip kHayTakes[2] = {" + clip('hay_a') + ", " + clip('hay_b') + "};",
          "const HorseClip kTootClip = " + clip('toot') + ";", "", "}  // namespace squatch"]
open(out, 'w').write("\n".join(lines) + "\n")
